    /// <summary>
    /// Draws one character into an image, scaled up, centered in a square cell.
    /// Uppercase letters draw as lowercase; unknown characters draw nothing.
    /// </summary>
    public static void Draw(Image image, char c, int cellX, int cellSize, Color color, int scale = 2)
    {
        if (!Glyphs.TryGetValue(char.ToLowerInvariant(c), out var rows))
            return;

        int left = cellX + (cellSize - 3 * scale) / 2;
        int top = (cellSize - 5 * scale) / 2;
        for (int y = 0; y < 5; y++)
        {
            for (int x = 0; x < 3; x++)
            {
                if (rows[y][x] == '1')
                    image.FillRect(new Rect2I(left + x * scale, top + y * scale, scale, scale), color);
            }
        }
    }
